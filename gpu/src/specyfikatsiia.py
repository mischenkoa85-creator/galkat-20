def n(v, nd=1):
    if v is None or v == '': return ''
    if isinstance(v, str): return v
    s = ('%.' + str(nd) + 'f') % v
    if nd and '.' in s:
        pass
    return s.replace('.', ',')


def ni(v): return '{:,}'.format(int(round(v))).replace(',', ' ')
def t3(kg): return n(kg / 1000.0, 3)


