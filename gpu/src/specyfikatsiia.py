def draw_doc(path):
    from reportlab.pdfgen import canvas
    from reportlab.lib.units import mm
    # двопрохідна верстка: спершу рахуємо кількість аркушів
    for pass_ in (0, 1):
        out = path if pass_ else os.devnull
        c = canvas.Canvas(out, pagesize=(PW * mm, PH * mm))
        c.setTitle('ГалКат, площадка 20: специфікація матеріалів і відомість обсягів робіт — фундаменти BESS і PCS')
        c.setAuthor('За кресленнями комплекту «ГПУ, BESS, КЛ-6 кВ», стадія Р')
        c.setSubject('Фундаменти BESS і PCS, варіанти 1,80 м і 1,50 м')
        p = M.Pen(c)
        st = {'page': 1, 'y': 287.0, 'bottom': 64.0}
        total = TOTAL_PAGES[0] if pass_ else 99

        def stamp_page():
            if st['page'] == 1:
                stamp.draw(p, MS, TITLE, '—', 1, total, SRC)
            else:
                stamp.draw_next(p, MS, SHORT, st['page'])

        def next_page():
            stamp_page(); c.showPage()
            st['page'] += 1; st['y'] = 287.0; st['bottom'] = 24.0

        def need(h):
            if st['y'] - h < st['bottom']:
                next_page(); return True
            return False

        def heading(t, size=10.0):
            need(12)
            p.text(20 + 2, st['y'] - 4.0, t, size, 'B'); st['y'] -= 4.0 + 4.0

        def para(t, size=7.4, ind=0.0, num=None):
            lines = stamp.wrap(p, t, 181 - ind - (5 if num else 0), size)
            need(len(lines) * 3.3 + 1)
            x = 22 + ind
            if num: p.text(x, st['y'] - 3.0, num, size)
            yy = st['y'] - 3.0
            for ln in lines:
                p.text(x + (5 if num else 0), yy, ln, size); yy -= 3.3
            st['y'] = yy + 3.3 - 4.4

        def table(cols, rows, size=6.9, head_h=8.0):
            xs = [20.0]
            for w_ in cols: xs.append(xs[-1] + w_[1])
            def header():
                need(head_h + 6)
                y0 = st['y']
                p.rect(20, y0 - head_h, 185, head_h, w=0.35, fill=GREY)
                for i, (t, w_, al) in enumerate(cols):
                    ls = t.split('\n')
                    yy = y0 - head_h / 2 + (len(ls) - 1) * 1.5 - 0.9
                    for ln in ls:
                        p.text(xs[i] + w_ / 2, yy, ln, 6.4, 'B', anchor='c'); yy -= 3.0
                    if i: p.line(xs[i], y0, xs[i], y0 - head_h, 0.25)
                st['y'] = y0 - head_h
            header()
            for r in rows:
                if r[0] == 'g':
                    if st['y'] - 5.4 - 4.6 < st['bottom']:
                        p.line(20, st['y'], 205, st['y'], 0.35); next_page(); header()
                    y0 = st['y']
                    p.rect(20, y0 - 5.4, 185, 5.4, w=0.25, fill=(0.97, 0.97, 0.98))
                    p.text(22, y0 - 3.8, r[1], 7.2, 'B'); st['y'] -= 5.4
                    continue
                cells = []
                for i, (t, w_, al) in enumerate(cols):
                    v = r[i] if i < len(r) else ''
                    f = 'R'
                    cells.append(stamp.wrap(p, v, w_ - 2.0, size, f) if al == 'l' else [v])
                hrow = max(len(cl) for cl in cells) * 3.0 + 1.25
                if st['y'] - hrow < st['bottom']:
                    p.line(20, st['y'], 205, st['y'], 0.35); next_page(); header()
                y0 = st['y']
                for i, (t, w_, al) in enumerate(cols):
                    yy = y0 - 2.85
                    for ln in cells[i]:
                        sz = stamp.fit(p, ln, w_ - 1.6, size) if al != 'l' else size
                        if al == 'l': p.text(xs[i] + 1.0, yy, ln, sz)
                        elif al == 'c': p.text(xs[i] + w_ / 2, yy, ln, sz, anchor='c')
                        else: p.text(xs[i + 1] - 1.0, yy, ln, sz, anchor='r')
                        yy -= 3.05
                    if i: p.line(xs[i], y0, xs[i], y0 - hrow, 0.2)
                p.line(20, y0 - hrow, 205, y0 - hrow, 0.15, (0.6, 0.62, 0.65))
                st['y'] -= hrow
            p.line(20, st['y'], 205, st['y'], 0.35)
            st['y'] -= 4.0

        # ---------------- аркуш 1: загальні дані і основні показники
        p.text(22, 282.0, 'Специфікація матеріалів і відомість обсягів робіт', 13.0, 'B')
        p.text(22, 276.2, 'Фундаменти BESS і PCS, кабельний канал, заземлення, майданчик обслуговування · два варіанти фундаменту', 8.0, col=M.MUTED)
        st['y'] = 271.0
        heading('Загальні дані', 9.4)
        for i, t in enumerate(GENERAL, 1):
            para(t, 7.4, num='%d.' % i)
        st['y'] -= 1.0
        heading('Основні показники', 9.4)
        table([('Показник', 105, 'l'), ('Варіант 1\nниз −1,850', 40, 'r'), ('Варіант 2\nниз −1,500', 40, 'r')], SUMMARY(), size=7.0)
        heading('Порядок виконання', 9.4)
        for i, t in enumerate(ORDER, 1):
            para(t, 7.2, num='%d.' % i)
        # ---------------- специфікація
        next_page()
        heading('1. Специфікація матеріалів')
        p.text(22, st['y'] + 1.2, 'кількість — на обидва фундаменти (BESS і PCS), канал, заземлення і майданчик разом', 6.6, col=M.MUTED); st['y'] -= 2.0
        table([('Поз.', 9, 'c'), ('Найменування і марка', 79, 'l'), ('Од.', 13, 'c'), ('Варіант 1\n1,80 м', 19, 'r'), ('Варіант 2\n1,50 м', 19, 'r'), ('Примітка', 46, 'l')], spec_rows())
        # ---------------- відомість обсягів робіт
        need(40)
        heading('2. Відомість обсягів робіт')
        p.text(22, st['y'] + 1.2, 'у порядку виконання; обсяги — нетто, без коефіцієнтів на розпушення', 6.6, col=M.MUTED); st['y'] -= 2.0
        table([('№', 10, 'c'), ('Найменування робіт', 82, 'l'), ('Од.', 14, 'c'), ('Варіант 1\n1,80 м', 18, 'r'), ('Варіант 2\n1,50 м', 18, 'r'), ('Примітка', 43, 'l')], works_rows())
        heading('3. Безпека робіт біля мереж', 9.4)
        for i, t in enumerate(SAFETY, 1):
            para(t, 7.2, num='%d.' % i)
        stamp_page()
        c.save()
        TOTAL_PAGES[0] = st['page']
    return TOTAL_PAGES[0]


